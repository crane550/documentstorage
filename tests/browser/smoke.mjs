import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { credentials, chromiumPath, signIn, connectStorage, openFolder, enterFolder, newFolder, fileRow, toast, nav, noOverflow } from './ui.mjs';

const base = process.env.DOCUMENTSTORAGE_TEST_URL || 'http://127.0.0.1:5240';
assert(['localhost','127.0.0.1','[::1]'].includes(new URL(base).hostname), 'Only test local development instances');
const directory = path.resolve(process.env.DOCUMENTSTORAGE_BROWSER_ROOT || '.local/browser-storage');
await mkdir(path.join(directory, 'Reference'), { recursive: true });
await writeFile(path.join(directory, 'Reference', 'welcome.txt'), 'Synthetic document workspace. Files are stored locally and remain ordinary files.');
const browser = await chromium.launch({ executablePath: chromiumPath(), args: ['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
let count = 0;
async function check(condition, description) { assert(await condition, description); count++; console.log('PASS '+description); }
try {
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', {name:'Sign in', exact:true}).waitFor();
    await signIn(page, await credentials());
    await page.waitForURL(url => url.pathname === '/');
    await check(page.locator('.shell').count().then(n=>n===1), 'built-in login opens the interactive workspace');
    await connectStorage(page, base, 'Sample archive', directory);
    await fileRow(page, 'Reference').waitFor();
    await check(fileRow(page, 'Reference').count().then(n => n > 0), 'storage connection discovers existing folders');
    const stamp = Date.now().toString();
    const folder = 'Statements '+stamp;
    await newFolder(page, folder);
    await check(page.locator('.page-head h1').filter({hasText:'Sample archive'}).count().then(n=>n===1), 'creating a folder keeps you in the current folder');
    await enterFolder(page, folder);
    await page.getByRole('button',{name:'Edit folder notes',exact:true}).click();
    await page.getByRole('textbox',{name:'Folder notes',exact:true}).fill('Monthly bank statements. Use the statement closing date in the name.');
    await page.getByRole('button',{name:'Save note',exact:true}).click();
    await toast(page, 'Note saved.');
    await page.reload(); await page.locator('.sticky-note .instruction-canonical').waitFor();
    await check(page.locator('.sticky-note .instruction-canonical').textContent().then(t=>t.includes('closing date')), 'folder notes persist after a reload');
    const filename='synthetic-'+stamp+'.txt';
    await page.getByLabel('Upload documents').setInputFiles({name:filename,mimeType:'text/plain',buffer:Buffer.from('Synthetic October statement. Search phrase: copper lantern '+stamp+'. Balance 42.50.')});
    await fileRow(page, filename).waitFor();
    await page.getByLabel('Search documents').fill('copper lantern '+stamp);
    await page.getByLabel('Search documents').press('Enter');
    await page.locator('.page-head h1').filter({hasText:'Search'}).waitFor();
    await fileRow(page, filename).waitFor();
    await check(page.locator('.file-name').count().then(n=>n===1), 'search finds extracted document contents');
    await fileRow(page, filename).click();
    await check(page.locator('.text-preview').textContent().then(t=>t.includes('42.50')), 'document detail shows indexed text');
    const downloadReady = page.waitForEvent('download');
    await page.locator('.details').getByRole('link',{name:'Download original',exact:true}).click();
    const download = await downloadReady;
    await check(readFile(await download.path(),'utf8').then(t=>t.includes('42.50')), 'download returns original document bytes');
    await page.getByRole('button',{name:'Rename or move',exact:true}).click();
    await page.getByLabel('Name',{exact:true}).fill('2026-10-31 - Cedar '+stamp+'.txt');
    await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await check(readFile(path.join(directory,folder,'2026-10-31 - Cedar '+stamp+'.txt'),'utf8').then(t=>t.includes('42.50')), 'browser rename changes the real file without changing its bytes');
    await page.getByRole('button',{name:'Move selected item to trash',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Move to trash',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await nav(page, 'Trash');
    await page.locator('.activity-row').filter({hasText:'Cedar '+stamp}).getByRole('button',{name:'Restore',exact:true}).click();
    await toast(page, 'restored');
    await check(readFile(path.join(directory,folder,'2026-10-31 - Cedar '+stamp+'.txt'),'utf8').then(t=>t.includes('42.50')), 'browser trash and restore preserve document contents');
    await nav(page, 'History');
    await page.locator('.activity-row').first().waitFor();
    await check(page.locator('.activity-row').count().then(n=>n>=3), 'file operations appear in history');
    await openFolder(page, 'Sample archive');
    await page.screenshot({path:process.env.DOCUMENTSTORAGE_SCREENSHOT || '.local/workspace.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await check(noOverflow(page), 'mobile layout does not overflow horizontally');
    await page.getByRole('button',{name:'Open menu',exact:true}).click();
    await page.locator('.account-link').click();
    await page.getByRole('button', {name:'Sign out',exact:true}).click();
    await page.waitForURL(url => url.pathname === '/login');
    await page.goto(base);
    await check(Promise.resolve(new URL(page.url()).pathname === '/login'), 'sign-out returns to login and protects the workspace');
    await check(failures.length===0, 'no browser JavaScript errors');
    console.log(`All ${count} browser checks passed.`);
} finally { await browser.close(); }
