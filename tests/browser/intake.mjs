import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { credentials, chromiumPath, signIn, connectStorage, enterFolder, newFolder, fileRow, toast, nav, inbox, useAsInbox, settleAndRescan, noOverflow, openInboxItem } from './ui.mjs';

const base = process.env.DOCUMENTSTORAGE_TEST_URL || 'http://127.0.0.1:5240';
assert(['localhost','127.0.0.1','[::1]'].includes(new URL(base).hostname), 'Use only a disposable local instance');
const directory = path.resolve('.local/intake-browser-storage');
await mkdir(directory,{recursive:true});
const browser = await chromium.launch({executablePath:chromiumPath(),args:['--no-sandbox','--disable-dev-shm-usage']});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
let checks=0;
async function check(value,label){assert(await value,label);checks++;console.log('PASS '+label);}
try {
    await page.goto(base);
    await signIn(page, await credentials());
    await connectStorage(page, base, 'Intake test archive', directory);
    const stamp=Date.now().toString();
    const incoming='Incoming '+stamp, archive='Filed '+stamp, source='scan-'+stamp+'.txt';
    for (const folder of [incoming,archive]) await newFolder(page, folder);
    await enterFolder(page, incoming);
    await useAsInbox(page);
    await check(page.locator('.tree-label').filter({hasText:incoming}).locator('.tree-tag').count().then(n=>n===1),'a folder becomes an inbox through the real UI and is marked in the sidebar');
    const content='Synthetic monthly bank statement. Statement ends 2026-10-31. Account 1234. Balance 42.50.';
    await page.getByLabel('Upload documents').setInputFiles({name:source,mimeType:'text/plain',buffer:Buffer.from(content)});
    await fileRow(page, source).waitFor();
    // The production stability window is intentional, rather than a renderer synchronization delay.
    await settleAndRescan(page);
    await inbox(page);
    await openInboxItem(page, source);
    await check(page.locator('.slip-text pre').textContent().then(t=>t.includes('42.50')),'the filing slip shows the actual extracted document text');
    const type='statement_'+stamp, bank='Cedar-'+stamp, suffix=stamp.slice(-4);
    await page.getByLabel('Document type',{exact:true}).fill(type);
    await page.locator('.destination.pending').filter({hasText:'No rule files this yet'}).waitFor();
    await check(Promise.resolve(true),'an unknown document explains that no rule files it yet');
    for (const [index,[name,value]] of [['institution',bank],['account_suffix',suffix],['statement_end','2026-10-31']].entries()) {
        if (index > 0) await page.getByRole('button',{name:'Add fact',exact:true}).click();
        await page.getByLabel('Fact name',{exact:true}).nth(index).fill(name);
        await page.getByLabel('Fact value',{exact:true}).nth(index).fill(value);
    }
    await page.getByRole('button',{name:'Confirm facts',exact:true}).click();
    await toast(page,'Facts confirmed.');
    await nav(page,'Rules');
    await page.locator('.page-head').getByRole('button',{name:'New rule',exact:true}).click();
    const ruleName='Cedar statements '+stamp;
    await page.getByLabel('Rule name',{exact:true}).fill(ruleName);
    await page.getByLabel('Document type',{exact:true}).fill(type);
    await page.getByLabel('Condition name',{exact:true}).fill('institution');
    await page.getByLabel('Condition value',{exact:true}).fill(bank);
    await page.getByLabel('Destination folder',{exact:true}).selectOption({label:'Intake test archive / '+archive});
    await page.getByLabel('Filename pattern',{exact:true}).fill('{statement_end:yyyy-MM-dd} - {institution} - {account_suffix}.{extension}');
    await page.getByLabel('Use this rule when filing',{exact:true}).uncheck();
    await page.getByRole('button',{name:'Save rule',exact:true}).click();
    await toast(page,'Rule saved.');
    await page.getByRole('button',{name:'Try on inbox',exact:true}).click();
    await page.locator('.simulation-row').filter({hasText:source}).getByText('Matches',{exact:true}).waitFor();
    await check(readFile(path.join(directory,incoming,source),'utf8').then(t=>t===content),'trying a paused rule previews the name without moving the source');
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
    const card=page.locator('.rule-card').filter({hasText:ruleName});
    await card.getByRole('switch',{name:'Use '+ruleName,exact:true}).click();
    await toast(page,'is on.');
    await card.locator('.stamp').filter({hasText:'On'}).waitFor();
    await card.getByRole('button',{name:'Edit',exact:true}).click();
    await check(page.locator('.rule-history summary').textContent().then(t=>t.includes('2')),'turning the rule on keeps its version history');
    await page.screenshot({path:'.local/filing-rules.png',fullPage:true});
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
    await inbox(page);
    await openInboxItem(page, source);
    const target='2026-10-31 - '+bank+' - '+suffix+'.txt';
    await page.locator('.destination.ready .destination-name').filter({hasText:target}).waitFor();
    await check(page.locator('.destination.ready .folder-tab').textContent().then(t=>t.includes(archive)),'the slip shows the exact destination folder and filename before filing');
    await page.screenshot({path:'.local/intake-preview.png',fullPage:true});
    await page.getByRole('button',{name:'Confirm & file',exact:true}).click();
    await toast(page,'Filed as '+target);
    await check(readFile(path.join(directory,archive,target),'utf8').then(t=>t===content),'confirming files the actual document without altering its bytes');
    await check(page.locator('.intake-item').filter({hasText:source}).count().then(n=>n===0),'a filed document leaves the inbox');
    await nav(page,'History');
    await page.locator('.activity-row').filter({hasText:source}).waitFor();
    await check(page.locator('.activity-row').filter({hasText:source}).textContent().then(t=>t.includes('Completed')),'filing is recorded in the operation history');
    await nav(page,'Rules');
    await page.locator('.rule-card').filter({hasText:ruleName}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await check(noOverflow(page),'rules and navigation fit the mobile viewport');
    await check(errors.length===0,'inbox and rules have no browser JavaScript errors');
    console.log(`All ${checks} intake browser checks passed.`);
} finally {await browser.close();}
